//! Rasterize viewport lines to a PNG (no scrollback — only the lines passed in).

use anyhow::{Result, bail};
use image::{ImageBuffer, ImageFormat, Rgb, RgbImage};

/// Pixel size per character cell.
const CELL_W: u32 = 8;
const CELL_H: u32 = 16;
const PAD: u32 = 4;

const FG: Rgb<u8> = Rgb([0xd0, 0xd0, 0xd0]);
const BG: Rgb<u8> = Rgb([0x0b, 0x0b, 0x0c]);

/// Encode monospaced viewport `lines` (length ≤ rows, each ≤ cols) as PNG bytes.
pub fn viewport_png(lines: &[String], cols: u16, rows: u16) -> Result<Vec<u8>> {
    let cols = cols.max(1) as u32;
    let rows = rows.max(1) as u32;
    if cols > 500 || rows > 200 {
        bail!("viewport too large for remote frame");
    }
    let width = cols * CELL_W + PAD * 2;
    let height = rows * CELL_H + PAD * 2;
    let mut img: RgbImage = ImageBuffer::from_pixel(width, height, BG);

    for (r, line) in lines.iter().enumerate() {
        if r as u32 >= rows {
            break;
        }
        let y0 = PAD + r as u32 * CELL_H;
        for (c, ch) in line.chars().enumerate() {
            if c as u32 >= cols {
                break;
            }
            let x0 = PAD + c as u32 * CELL_W;
            draw_char(&mut img, x0, y0, ch, FG);
        }
    }

    let mut buf = Vec::new();
    let mut cursor = std::io::Cursor::new(&mut buf);
    img.write_to(&mut cursor, ImageFormat::Png)?;
    Ok(buf)
}

fn draw_char(img: &mut RgbImage, x0: u32, y0: u32, ch: char, color: Rgb<u8>) {
    let glyph = glyph_for(ch);
    for row in 0..7u32 {
        let bits = glyph[row as usize];
        for col in 0..5u32 {
            if bits & (1 << (4 - col)) != 0 {
                // Scale 5×7 into 8×16 cell with padding.
                let px = x0 + 1 + col;
                let py = y0 + 3 + row * 2;
                put(img, px, py, color);
                put(img, px, py + 1, color);
            }
        }
    }
}

fn put(img: &mut RgbImage, x: u32, y: u32, color: Rgb<u8>) {
    if x < img.width() && y < img.height() {
        img.put_pixel(x, y, color);
    }
}

