#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn png_matches_viewport_dims() {
        let lines = vec!["hello".into(), "world".into()];
        let png = viewport_png(&lines, 8, 2).unwrap();
        assert!(png.starts_with(&[0x89, b'P', b'N', b'G']));
        // dims: 8*8+8 = 72 wide, 2*16+8 = 40 tall — just check non-trivial size
        assert!(png.len() > 50);
    }

    #[test]
    fn ignores_extra_line_content_beyond_cols() {
        let lines = vec!["abcdefghijklmnop".into()];
        let png = viewport_png(&lines, 4, 1).unwrap();
        assert!(png.starts_with(&[0x89, b'P', b'N', b'G']));
    }
}
